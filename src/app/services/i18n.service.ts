@Injectable({
  providedIn: 'root',
})
export class I18nService {
  readonly supportedLanguages = SUPPORTED_LANGUAGES;
  readonly currentLanguage = signal<string>(this.detectLanguage());

  private detectLanguage(): string {
    try {
      const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
      if (saved && this.isSupported(saved)) {
        return saved;
      }
    } catch {
      /* ignore storage error */
    }

    let browserLang = 'en';
    if (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage) {
      browserLang = chrome.i18n.getUILanguage();
    } else if (typeof navigator !== 'undefined' && navigator.language) {
      browserLang = navigator.language;
    }

    const primaryCode = browserLang.split('-')[0].toLowerCase();
    return this.isSupported(primaryCode) ? primaryCode : 'en';
  }

  isSupported(code: string): boolean {
    return SUPPORTED_LANGUAGES.some((lang) => lang.code === code);
  }

  setLanguage(code: string): void {
    if (!this.isSupported(code)) return;
    this.currentLanguage.set(code);
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, code);
    } catch {
      /* ignore */
    }
  }

  t(key: string, params?: Record<string, string | number>): string {
    const lang = this.currentLanguage();
    const template = translations[lang]?.[key] ?? translations['en']?.[key] ?? key;
    if (!params) return template;

    return Object.entries(params).reduce((acc, [paramKey, value]) => {
      return acc.replace(new RegExp(`{{\\s*${paramKey}\\s*}}`, 'g'), String(value));
    }, template);
  }
}
